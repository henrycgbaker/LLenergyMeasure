#!/usr/bin/env python3
"""Absorb: the one command a maintainer runs per engine-version bump.

Drives the full knowledge-refresh loop for ONE engine's validation rules:
cold read (analyst proposes candidates) -> pool union (analyst + observed
collisions + manual seeds, deduped) -> recall interrogation (for each shipped
rule the fresh pool did not rediscover, one targeted "is this still present?"
query) -> verification ladder (citation check on the host, then construction /
identity probes in the engine container; the engine is the arbiter) -> promotion
(regenerate the shipped rules corpus from confirmed candidates and surviving
rules) -> review delta (mechanical old-vs-new diff for the maintainer).

Maintainer tooling, not part of the llem CLI. The only src/ file it writes is
the shipped rules corpus, and only through the promotion path. Every stage is
independently skippable so a re-run resumes rather than redoing finished work.
Pools are read/written only through :mod:`scripts._candidate_pool`; the corpus
is regenerated byte-stably (identical inputs produce identical bytes).

The ladder probes the SHIPPED rules directly alongside the pool: the analyst can
only express a cross-field relation as a ``present`` spec that the construction
probe cannot confirm, so probing each shipped rule's precise spec re-confirms
survivors and prevents false-retirement. Survival is decided on verdict STATUS,
never on the probe exit code (which is 0 even when every verdict is infra_error).

Run: python scripts/absorb.py --engine vllm --source-root SRC/ [--dry-run]
"""

